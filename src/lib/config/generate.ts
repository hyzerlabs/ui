export function generateCss(resolved: ResolvedConfig, options: GenerateOptions = {}): string {
	const mode = options.mode ?? 'full';
	const selector = options.selector ?? resolved.selector ?? ':root';
	// R2's backstop: the only guard a direct engine caller (gen-tokens.ts, a
	// docs page, a consumer build script) ever gets, since resolveConfig's own
	// check never sees a value passed straight through the option.
	assertSelector(selector, 'config.selector');
	return mode === 'full'
		? generateFull(resolved, selector, options.intro)
		: generateOverrides(resolved, selector, options.intro);
}

/** Weave optional intro lines into a generated header comment. */
function withIntro(header: string, intro: string[] | undefined): string {
	if (!intro || intro.length === 0) return header;
	const lines = header.split('\n');
	// After the opening '/**': the intro block, a spacer, then the stock text.
	return [lines[0], ...intro.map((l) => ` * ${l}`.trimEnd()), ' *', ...lines.slice(1)].join('\n');
}

/**
 * R4 — a scoped sheet's header names its scope, one line, immediately after
 * the identity line (`lines[1]`) and nothing else changes. `:root` gains
 * nothing, so an unscoped sheet's header is untouched. Applied before
 * `withIntro`, whose own insertion point (right after the opening `/**`) is
 * unaffected by a line further down.
 */
function withScope(header: string, selector: string): string {
	if (selector === ':root') return header;
	const lines = header.split('\n');
	return [lines[0], lines[1], ` * Scope: ${selector}`, ...lines.slice(2)].join('\n');
}

function generateFull(resolved: ResolvedConfig, selector: string, intro?: string[]): string {
	const parts: string[] = [withIntro(withScope(FULL_HEADER, selector), intro), `${selector} {`];

	resolved.sections.forEach((section, i) => {
		if (i > 0) parts.push('');
		parts.push(banner(SECTION_BANNERS[section.id], '\t'));
		parts.push(...declarations(section.entries, '\t', true));
		if (section.id === 'space') {
			parts.push('');
			parts.push(note(TOKEN_NOTES['--hz-density'], '\t'));
			parts.push(`\t--hz-density: ${resolved.density.unit};`);
		}
	});
	parts.push('}');

	parts.push('', DENSITY_COMMENT, densityBlock(resolved));

	// Every named theme is a [data-theme="<name>"] block of the same shape;
	// dark is one of them, and leads because the base itself authors it.
	const blocks = [resolved.dark, ...resolved.themes].map((theme) => ({
		theme,
		...themeBlock(resolved, theme)
	}));

	for (const { theme, own, dependents } of blocks) {
		const comment = theme.name === 'dark' ? DARK_COMMENT : themeComment(theme.name);
		parts.push('', comment, `${themeSelector(selector, theme.name)} {`);
		// Roles, then hues, then intents — sourced directly from the three
		// resolved lists (.3); no value-shape inference.
		parts.push(...declarations(theme.color, '\t', false));
		for (const group of [theme.palette, theme.intent, theme.rest]) {
			if (group.length === 0) continue;
			parts.push('');
			parts.push(...declarations(group, '\t', false));
		}
		if (dependents.length > 0) {
			parts.push('');
			parts.push(note(DERIVED_COMMENT, '\t'));
			parts.push(...declarations(dependents, '\t', false));
		}
		parts.push('}');

		// The system default carries the theme's OWN declarations only: it
		// applies at :root, where the chain declared above it re-resolves on
		// the same element, so the derived block would be pure duplication.
		if (theme.name === 'dark' && selector === ':root') {
			parts.push(
				'',
				systemComment(resolved.defaultThemeName),
				'@media (prefers-color-scheme: dark) {'
			);
			parts.push('\t:root:not([data-theme]) {');
			parts.push(...declarations(own, '\t\t', false));
			parts.push('\t}');
			parts.push('}');
		}
	}

	const restore = defaultRestore(resolved, blocks);
	if (restore.length > 0) {
		parts.push(
			'',
			defaultComment(resolved.defaultThemeName),
			`${themeSelector(selector, resolved.defaultThemeName)} {`
		);
		parts.push(...declarations(restore, '\t', false));
		parts.push('}');
	}

	parts.push(...customIntentSection(resolved, selector));
	parts.push(...componentHookSection(resolved, selector));

	return parts.join('\n') + '\n';
}

/**
 * The default block (`[data-theme="<resolved.defaultThemeName>"]`): every
 * token any theme block declares, restored to its default value.
 *
 * A token a theme introduces but `:root` never defines (a consumer's
 * dark-only intent, say) restores to `initial` — the guaranteed-invalid
 * value, which is what "not declared here" means for a custom property, so
 * `var()` falls back exactly as it does outside the theme.
 *
 * `--hz-density` is the one exception: it lives outside `resolved.sections`
 * (emitted by hand inside the `space` section), so it is never "not declared
 * here" — a theme that sets `density.unit` must restore to the root unit,
 * never `initial`, or every `calc(var(--hz-density) * N)` in the ladder goes
 * invalid at computed-value time. Spliced into root order right after the
 * space section's entries, where the full sheet emits it.
 */
function defaultRestore(
	resolved: ResolvedConfig,
	blocks: { own: TokenEntry[]; dependents: TokenEntry[] }[]
): TokenEntry[] {
	const changed = new Set<string>();
	for (const block of blocks) {
		for (const e of [...block.own, ...block.dependents]) changed.add(e.cssName);
	}
	const densityEntry: TokenEntry = {
		cssName: '--hz-density',
		key: 'density',
		value: resolved.density.unit,
		fromConfig: false
	};
	// :root order, so the block reads like the sheet it restores; tokens no
	// :root section defines follow at the end.
	const rootEntries = resolved.sections.flatMap((s) =>
		s.id === 'space' ? [...s.entries, densityEntry] : s.entries
	);
	const defined = new Set(rootEntries.map((e) => e.cssName));
	return [
		...rootEntries.filter((e) => changed.has(e.cssName)),
		...[...changed]
			.filter((cssName) => !defined.has(cssName))
			.map((cssName) => ({ cssName, key: cssName, value: 'initial', fromConfig: false }))
	];
}

function generateOverrides(resolved: ResolvedConfig, selector: string, intro?: string[]): string {
	const scoped = selector !== ':root';
	const header = withIntro(
		withScope(
			[
				'/**',
				' * @hyzer-labs/ui token overrides',
				' *',
				' * GENERATED FILE - do not edit by hand (hyzer generate --mode overrides).',
				...(scoped
					? [
							' * Config-touched tokens, plus every token that derives from them. A',
							' * scoped sheet must re-declare the derived Layer-2 chain: a var()',
							' * indirection declared at :root already resolved there, and inherits',
							' * down as a fixed value.',
							' * Import this sheet AFTER @hyzer-labs/ui/tokens.css so the overrides',
							' * win by source order.'
						]
					: [
							' * This sheet carries only the tokens your config touched. Import it',
							' * AFTER @hyzer-labs/ui/tokens.css so the overrides win by source order.'
						]),
				' */'
			].join('\n'),
			selector
		),
		intro
	);

	// Scoped sheets carry the derived chain too — see scopedClosure().
	const emit = scoped ? scopedClosure(resolved) : null;
	const rootEntries = resolved.sections.flatMap((s) =>
		s.entries.filter((e) => (emit ? emit.has(e.cssName) : e.fromConfig))
	);

	/**
	 * The dark block needs the same treatment for a different reason. A base
	 * dark entry like surface-muted's stronger tint
	 * (`color-mix(… var(--hz-palette-gray) 25%, var(--hz-color-surface))`) is
	 * declared at :root's dark block. Scoped, it never reaches the subtree, and
	 * the scope's own light-block declaration would silently keep applying its
	 * 6% light-mode tint in dark. Re-emit any dark entry that derives from a
	 * token the scope redeclares.
	 */
	const darkDerives = (e: TokenEntry) =>
		emit !== null && varRefs(e.value).some((ref) => emit.has(ref));
	/**
	 * R1 — the sheet emits the dark theme's own value for every token the
	 * sheet declares at its root, not only what the consumer authored under
	 * `themes.dark`. Otherwise the cascade disagrees with full mode: a root
	 * override with no dark counterpart falls through to the base sheet's dark
	 * block on whatever element carries data-theme="dark", while the contrast
	 * report grades resolved.dark — which always has the seeded companion.
	 */
	const rootNames = new Set(rootEntries.map((e) => e.cssName));
	const keepDark = (e: TokenEntry) => e.fromConfig || rootNames.has(e.cssName) || darkDerives(e);
	const darkEntries = [
		...resolved.dark.color.filter(keepDark),
		...resolved.dark.palette.filter(keepDark),
		...resolved.dark.intent.filter(keepDark),
		...resolved.dark.rest.filter(keepDark)
	];

	const parts: string[] = [header];
	const hasRoot = rootEntries.length > 0 || resolved.density.unitFromConfig;

	/**
	 * The light block below re-restores the tokens this sheet overrides, and it
	 * draws them from `rootEntries` — the same names with the same values. When
	 * every restored token is one this sheet already declares at the root, the
	 * two blocks would carry identical declarations, so they share one rule
	 * instead. Any token the root declares and light does not is a token no
	 * theme changes, which makes declaring it under light harmless.
	 */
	const restorableNames = new Set(
		defaultRestore(resolved, [
			themeBlock(resolved, resolved.dark),
			...resolved.themes.map((theme) => themeBlock(resolved, theme))
		]).map((e) => e.cssName)
	);
	// A theme block declaring --hz-density forces mergeDefault off too — same
	// reason as unitFromConfig above (R5): the merged root+light rule would
	// declare the default unit at the scope selector and clobber a consumer's
	// own --hz-density override inside that scope.
	const mergeDefault =
		hasRoot &&
		rootEntries.some((e) => restorableNames.has(e.cssName)) &&
		!resolved.density.unitFromConfig &&
		!restorableNames.has('--hz-density');

	if (hasRoot) {
		parts.push(
			mergeDefault
				? `${selector},\n${themeSelector(selector, resolved.defaultThemeName)} {`
				: `${selector} {`
		);
		parts.push(...declarations(rootEntries, '\t', false));
		if (resolved.density.unitFromConfig) parts.push(`\t--hz-density: ${resolved.density.unit};`);
		parts.push('}');
	}
	if (darkEntries.length > 0) {
		if (hasRoot) parts.push('');
		parts.push(`${themeSelector(selector, 'dark')} {`);
		parts.push(...declarations(darkEntries, '\t', false));
		parts.push('}');
	}

	// Named themes are entirely the consumer's authoring — every entry is
	// fromConfig, so the whole block is an override by definition. Each still
	// carries its derived chain, for the same reason the full sheet's do.
	let emitted = hasRoot || darkEntries.length > 0;
	const themeBlocks = resolved.themes.map((theme) => ({ theme, ...themeBlock(resolved, theme) }));
	for (const { theme, own, dependents } of themeBlocks) {
		if (own.length === 0) continue;
		if (emitted) parts.push('');
		parts.push(`${themeSelector(selector, theme.name)} {`);
		parts.push(...declarations(own, '\t', false));
		if (dependents.length > 0) {
			parts.push('');
			parts.push(note(DERIVED_COMMENT, '\t'));
			parts.push(...declarations(dependents, '\t', false));
		}
		parts.push('}');
		emitted = true;
	}

	// The base sheet's light block restores the BASE defaults — which would
	// undo this sheet's own :root overrides inside a light-scoped section.
	// Re-restore the tokens this sheet redeclares, after it in source order.
	const restorable = new Set(
		defaultRestore(resolved, [themeBlock(resolved, resolved.dark), ...themeBlocks]).map(
			(e) => e.cssName
		)
	);
	const restore = mergeDefault ? [] : rootEntries.filter((e) => restorable.has(e.cssName));
	// --hz-density never lives in rootEntries (it's outside resolved.sections),
	// so a theme block that declares it is spliced in here, last — mirroring
	// where the root block puts it — rather than picked up by the filter above.
	if (restorable.has('--hz-density')) {
		restore.push({
			cssName: '--hz-density',
			key: 'density',
			value: resolved.density.unit,
			fromConfig: false
		});
	}
	if (restore.length > 0) {
		if (emitted) parts.push('');
		parts.push(`${themeSelector(selector, resolved.defaultThemeName)} {`);
		parts.push(...declarations(restore, '\t', false));
		parts.push('}');
		emitted = true;
	}

	const intentSection = customIntentSection(resolved, selector);
	if (intentSection.length > 0) emitted = true;
	const hookSection = componentHookSection(resolved, selector);
	if (hookSection.length > 0) emitted = true;

	if (!emitted) {
		parts.push('/* No overrides configured. */');
	}
	parts.push(...intentSection, ...hookSection);
	return parts.join('\n') + '\n';
}

