/**
 * Selector for a ROOT-targeted hook group: the sheet's own scope selector,
 * :where-wrapped for the same zero-specificity reason as targetSelectors()
 * below — a consumer rule for the property still wins regardless of source
 * order. No compound/descendant pair to emit here: targetSelectors() needs
 * one because a class can sit either inside the scope or ON it; a ROOT hook
 * has no class of its own to be ambiguous with — the scope selector itself
 * is the target.
 */
function rootTargetSelectors(selector: string): string[] {
	return [`:where(${selector})`];
}

/** One rule for every hook the config set on `on` — `.${on}`, or the sheet's root for a ROOT group. */
function componentHookRule(selector: string, on: string, entries: TokenEntry[]): string {
	const selectors =
		on === ROOT ? rootTargetSelectors(selector) : targetSelectors(selector, `.${on}`);
	const lines = [
		`${selectors.join(',\n')} {`,
		...entries.map((e) => `\t${e.cssName}: ${e.value};`),
		'}'
	];
	return lines.join('\n');
}

/**
 * Appended at the very end of the sheet, after the custom-intent section, in
 * both full and overrides mode. Empty when the config sets no hook. Grouped
 * by `on` (an owning class, or the ROOT sentinel — every ROOT hook shares one
 * rule), in `componentHooks` order; within a rule, the config's own key order
 * (`resolved.components` is already in that order, seeded from `[]`) — same
 * resolved config, same bytes.
 */
function componentHookSection(resolved: ResolvedConfig, selector: string): string[] {
	if (resolved.components.length === 0) return [];
	const byOn = new Map<string, TokenEntry[]>();
	for (const entry of resolved.components) {
		const hook = componentHooks.find((h) => h.name === entry.cssName)!;
		if (!byOn.has(hook.on)) byOn.set(hook.on, []);
		byOn.get(hook.on)!.push(entry);
	}
	const onOrder: string[] = [];
	for (const hook of componentHooks) {
		if (byOn.has(hook.on) && !onOrder.includes(hook.on)) onOrder.push(hook.on);
	}
	const parts: string[] = ['', banner(COMPONENT_HOOKS_BANNER, '')];
	for (const on of onOrder) parts.push('', componentHookRule(selector, on, byOn.get(on)!));
	return parts;
}

/** Custom-property names referenced by var() inside a token value. */
function varRefs(value: string): string[] {
	return [...value.matchAll(/var\(\s*(--[a-z0-9-]+)/gi)].map((m) => m[1]);
}

/**
 * The tokens a SCOPED override sheet must re-declare: everything the config
 * touched, plus the transitive closure of tokens whose values depend on them.
 *
 * Why this exists. The two-layer color model is built on indirection —
 * `--hz-intent-primary: var(--hz-palette-primary)` — and var() inside a custom
 * property is substituted at computed-value time ON THE ELEMENT THE
 * DECLARATION APPLIES TO. At `:root` that is exactly what we want: an
 * override of `--hz-palette-primary` lands on the same element as the intent
 * declaration, so the cascade picks the new value and the whole chain
 * re-resolves.
 *
 * Scoped to a class it breaks. `.theme-ocean { --hz-palette-primary: #0f766e }`
 * leaves `--hz-intent-primary` declared back at `:root`, where it already
 * computed to the BASE blue and inherits down as that resolved value — so
 * every component reading the intent vocabulary (Button, Badge, Alert) keeps
 * the base palette while the panel swears it is teal.
 *
 * Re-emitting the dependents under the scope re-resolves them against the
 * scope's own values. The seed includes dark-block entries: a hue overridden
 * only in dark still needs its intent chain declared locally, or the dark
 * block has nothing to feed.
 */
function closureFrom(resolved: ResolvedConfig, seed: Iterable<string>): Set<string> {
	const included = new Set<string>(seed);
	const all = resolved.sections.flatMap((s) => s.entries);
	for (let changed = true; changed; ) {
		changed = false;
		for (const e of all) {
			if (included.has(e.cssName)) continue;
			if (varRefs(e.value).some((ref) => included.has(ref))) {
				included.add(e.cssName);
				changed = true;
			}
		}
	}
	return included;
}

function scopedClosure(resolved: ResolvedConfig): Set<string> {
	const seed: string[] = [];
	for (const section of resolved.sections) {
		for (const e of section.entries) if (e.fromConfig) seed.push(e.cssName);
	}
	for (const e of themeOwn(resolved.dark)) {
		if (e.fromConfig) seed.push(e.cssName);
	}
	return closureFrom(resolved, seed);
}

/** A theme's own declarations, in emission order (roles, hues, intents, rest). */
function themeOwn(theme: ResolvedTheme): TokenEntry[] {
	return [...theme.color, ...theme.palette, ...theme.intent, ...theme.rest];
}

/**
 * A theme block: what the theme itself declares, plus the derived chain it
 * must re-declare to work on ANY element rather than only on `<html>`.
 *
 * Why the dependents exist. `--hz-intent-primary: var(--hz-palette-primary)`
 * is declared at `:root`, and var() inside a custom property is substituted
 * at computed-value time on the element the declaration applies to. When the
 * theme block lands on `<html>` — the same element as `:root` — the override
 * and the chain meet there and everything re-resolves. Land it on a
 * `<section>` instead and the intents have already computed at `:root` to the
 * default palette, inheriting down as fixed values: a dark section with
 * light-blue buttons and light borders. Re-declaring the dependents inside
 * the block re-resolves them against the theme's own values, on whatever
 * element the block matched. At `:root` they are identical to the defaults
 * and cost nothing but bytes.
 *
 * This is the same problem `scopedClosure()` solves for scoped sheets, from
 * the other direction: there the SHEET is scoped, here the BLOCK is.
 */
function themeBlock(
	resolved: ResolvedConfig,
	theme: ResolvedTheme
): { own: TokenEntry[]; dependents: TokenEntry[] } {
	const own = themeOwn(theme);
	const ownNames = new Set(own.map((e) => e.cssName));
	const closure = closureFrom(resolved, ownNames);
	const dependents = resolved.sections
		.flatMap((s) => s.entries)
		.filter((e) => closure.has(e.cssName) && !ownNames.has(e.cssName));
	return { own, dependents };
}

