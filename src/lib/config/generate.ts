function banner(lines: string[], indent: string): string {
	const bar = '='.repeat(69);
	return [
		`${indent}/* ${bar}`,
		...lines.map((l) => `${indent} * ${l}`),
		`${indent} * ${bar} */`
	].join('\n');
}

function note(lines: string[], indent: string): string {
	if (lines.length === 1) return `${indent}/* ${lines[0]} */`;
	return (
		[`${indent}/* ${lines[0]}`, ...lines.slice(1).map((l) => `${indent} * ${l}`)].join('\n') + ' */'
	);
}

function declarations(entries: TokenEntry[], indent: string, withNotes: boolean): string[] {
	const out: string[] = [];
	for (const entry of entries) {
		const noteLines = withNotes ? TOKEN_NOTES[entry.cssName] : undefined;
		if (noteLines) out.push(note(noteLines, indent));
		out.push(`${indent}${entry.cssName}: ${entry.value};`);
	}
	return out;
}

type DensityLevel = { near: number; away: number };

/** `--hz-density-ladder-depth-<n>` — the 1-based public rung name for a level. */
function densityRungName(depth: number): string {
	return `--hz-density-ladder-depth-${depth}`;
}

/**
 * The rung's own literal fallback: `config.tokens.density.ladder`'s value for
 * this depth when the config set one (specs/65 R21 — substituted verbatim,
 * not wrapped in another `calc()`), else `levels[depth - 1]`'s near
 * multiplier, exactly as before the config could touch this.
 */
function densityRungFallback(
	levels: readonly DensityLevel[],
	ladder: Readonly<Record<number, string>>,
	depth: number
): string {
	return ladder[depth] ?? `calc(var(--hz-density) * ${levels[depth - 1].near})`;
}

/** `var(--hz-density-ladder-depth-<n>, <its own literal fallback>)`. */
function densityRungRef(
	levels: readonly DensityLevel[],
	ladder: Readonly<Record<number, string>>,
	depth: number
): string {
	return `var(${densityRungName(depth)}, ${densityRungFallback(levels, ladder, depth)})`;
}

/**
 * Four rules — one per `density.levels` depth — each declaring
 * `--hz-space-near`/`--hz-space-away` as a `var()` lookup against a public
 * rung, never a bare `calc()`. No rung is ever declared here (R11): the
 * lookup form is what lets a consumer override a rung from ANYWHERE —
 * `:root`, a section, inside a `@layer` — with no cascade fight against an
 * unlayered declaration in this sheet.
 *
 * A level's `near` references its own depth's rung. Its `away` references
 * the next-shallower depth's rung — the ladder rule ("a level's away equals
 * the next-shallower level's near") — except at depth 1 (`body`), which has
 * no shallower rung: its away is its own rung, doubled. Both are asserted
 * against `density.levels` rather than assumed, so a metadata row that
 * breaks the ladder rule is a generator error naming the level, not a
 * silently unhooked declaration.
 */
function densityBlock(resolved: ResolvedConfig): string {
	const levels = resolved.density.levels;
	const ladder = resolved.density.ladder;
	const rules = levels.map((level, index) => {
		const depth = index + 1;
		const selector = index === 0 ? 'body' : `body ${'[data-density-shift] '.repeat(index).trim()}`;
		const near = densityRungRef(levels, ladder, depth);

		let away: string;
		if (index === 0) {
			if (level.away !== level.near * 2) {
				throw new HyzerConfigError(
					`density.levels[0].away (${level.away}) must equal density.levels[0].near x 2 ` +
						`(${level.near * 2}) - the top rung has no shallower rung to point at, so its away ` +
						'must be its own rung, doubled.'
				);
			}
			away = `calc(${near} * 2)`;
		} else {
			const prevNear = levels[index - 1].near;
			if (level.away !== prevNear) {
				throw new HyzerConfigError(
					`density.levels[${index}].away (${level.away}) must equal density.levels[${index - 1}].near ` +
						`(${prevNear}) - a level's away must equal the next-shallower level's near.`
				);
			}
			away = densityRungRef(levels, ladder, depth - 1);
		}

		return [
			`${selector} {`,
			`\t--hz-space-near: ${near};`,
			`\t--hz-space-away: ${away};`,
			'}'
		].join('\n');
	});
	return rules.join('\n\n');
}

/**
 * Theme-block selector: plain hook at :root, compound + descendant when scoped
 * (the scope element may carry data-theme itself, or inherit it from an
 * ancestor like <html>).
 *
 * The scoped pair is emitted one selector per line: generated sheets are
 * committed, so `prettier --check .` sees them, and a comma-joined pair of
 * this length is exactly what Prettier would break. Matching its output keeps
 * the drift test and the lint suite from contradicting each other.
 */
function themeSelector(selector: string, name: string): string {
	if (selector === ':root') return `[data-theme='${name}']`;
	return `${selector}[data-theme='${name}'],\n[data-theme='${name}'] ${selector}`;
}

